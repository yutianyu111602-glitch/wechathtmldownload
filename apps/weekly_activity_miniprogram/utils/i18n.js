function normalizeLang(value) {
  return value === "en" ? "en" : "zh";
}

function text(scope, lang) {
  const safeLang = normalizeLang(lang);
  return TEXT[scope]?.[safeLang] || TEXT[scope]?.zh || {};
}

function normalizeText(value) {
  return String(value || "")
    .toLowerCase()
    .replace(/[\s_\-·・.。/\\|｜,，()（）]/g, "")
    .trim();
}

function titleCase(value) {
  return String(value || "")
    .replace(/[_-]+/g, " ")
    .replace(/\s+/g, " ")
    .trim()
    .replace(/\b[a-z]/g, (char) => char.toUpperCase());
}

function cityKeyFor(value, key) {
  const fromKey = normalizeText(key);
  if (fromKey && CITY_LABELS[fromKey]) return fromKey;
  const fromValue = normalizeText(value);
  return CITY_ALIAS_TO_KEY[fromValue] || "";
}

function translateCity(value, lang, key) {
  const safeLang = normalizeLang(lang);
  const raw = String(value || key || "").trim();
  if (!raw) return "";
  const mappedKey = cityKeyFor(raw, key);
  if (mappedKey) return CITY_LABELS[mappedKey][safeLang];
  const rawKey = String(key || "").trim();
  if (safeLang === "en" && /^[a-z][a-z_\-\s]+$/i.test(rawKey)) return titleCase(rawKey);
  if (safeLang === "en" && /^[a-z][a-z_\-\s]+$/i.test(raw)) return titleCase(raw);
  return raw;
}

function compactDate(value) {
  const raw = String(value || "").trim();
  const match = raw.match(/^(\d{4})-(\d{2})-(\d{2})$/);
  if (!match) return raw;
  return `${match[2]}.${match[3]}`;
}

function isoDate(value) {
  const text = String(value || "").trim();
  return /^\d{4}-\d{2}-\d{2}$/.test(text) ? text : "";
}

function itemDateRange(item = {}) {
  const rangeMatch = String(item.dateRangeLabel || "").match(/^(\d{4}-\d{2}-\d{2})\s*-\s*(\d{4}-\d{2}-\d{2})$/);
  const start = isoDate(item.dateLabel || item.event_date_start || item.eventDateStart || (rangeMatch && rangeMatch[1]));
  const end = isoDate(item.event_date_end || item.eventDateEnd || (rangeMatch && rangeMatch[2]) || start);
  return { start, end: end && start && end >= start ? end : start };
}

function compactDateRange(start, end) {
  const safeStart = isoDate(start);
  const safeEnd = isoDate(end);
  if (!safeStart) return "";
  if (safeEnd && safeEnd !== safeStart) return `${compactDate(safeStart)}-${compactDate(safeEnd)}`;
  return compactDate(safeStart);
}

function weekdayLabel(value, lang) {
  const match = String(value || "").match(/^(\d{4})-(\d{2})-(\d{2})$/);
  if (!match) return "";
  const date = new Date(Number(match[1]), Number(match[2]) - 1, Number(match[3]));
  return WEEKDAYS[normalizeLang(lang)][date.getDay()] || "";
}

function weekdayRangeLabel(start, end, lang) {
  const safeStart = isoDate(start);
  const safeEnd = isoDate(end);
  if (!safeStart) return "";
  const startLabel = weekdayLabel(safeStart, lang);
  if (safeEnd && safeEnd !== safeStart) return `${startLabel}-${weekdayLabel(safeEnd, lang)}`;
  return startLabel;
}

function dateDisplay(value, lang) {
  const weekday = weekdayLabel(value, lang);
  const compact = compactDate(value);
  return [weekday, compact].filter(Boolean).join(" ");
}

function priceText(value, lang) {
  const safeLang = normalizeLang(lang);
  const raw = String(value || "").trim();
  if (!raw || safeLang === "zh") return raw;
  if (/^(免票|免费入场|免票入场|free\s*entry)$/i.test(raw)) return "Free Entry";
  const afterFree = raw.match(/^(.+?)\s*(后|之后|以后)\s*(免费入场|免票入场|免票)$/);
  if (afterFree) return `Free entry after ${afterFree[1].trim()}`;
  return raw
    .replace(/早鸟/g, "Early bird")
    .replace(/预售/g, "Presale")
    .replace(/双人/g, "Pair")
    .replace(/单人/g, "Single")
    .replace(/现场/g, "Door")
    .replace(/全价/g, "Full price")
    .replace(/学生/g, "Student")
    .replace(/门票|票价/g, "Ticket")
    .replace(/免费入场|免票入场|免票/g, "Free Entry")
    .replace(/元/g, " RMB");
}

function localizedSourceArticles(articles, lang) {
  const safeLang = normalizeLang(lang);
  return (Array.isArray(articles) ? articles : []).map((article) => {
    if (safeLang === "zh") return article;
    return {
      ...article,
      title: String(article.title || "")
        .replace(/排期原文$/g, "schedule source")
        .replace(/原文$/g, "source"),
      subtitle: String(article.subtitle || "")
        .replace(/发布\s*/g, "Published ")
        .replace(/(\d+)场/g, "$1 events"),
    };
  });
}

function localizeItem(item, lang) {
  const safeLang = normalizeLang(lang);
  const base = item || {};
  const isSourceOverview = Boolean(base.isSourceOverview);
  const rawCityLabel = base.rawCityLabel || base.cityLabel || (Array.isArray(base.city) ? base.city[0] : base.city) || base.city_key || "";
  const cityLabel = translateCity(rawCityLabel, safeLang, base.city_key);
  const rawPriceItems = base.rawPriceItems || base.price || [];
  const priceItems = (Array.isArray(rawPriceItems) ? rawPriceItems : [rawPriceItems])
    .filter(Boolean)
    .map((value) => priceText(value, safeLang));
  const rawCardLocation = base.rawCardLocationLabel || base.cardLocationLabel || "";
  const cityLikeCard = cityKeyFor(rawCardLocation, base.city_key) || normalizeText(rawCardLocation) === normalizeText(rawCityLabel);
  const cardLocationLabel = cityLikeCard ? cityLabel : rawCardLocation;
  const range = itemDateRange(base);
  const rangeLabel = isSourceOverview ? "" : base.dateRangeLabel || (range.start && range.end !== range.start ? `${range.start} - ${range.end}` : base.dateLabel);
  const weekday = isSourceOverview ? "" : weekdayRangeLabel(range.start, range.end, safeLang) || base.weekdayLabel || "";
  const dateCompactLabel = isSourceOverview ? "" : compactDateRange(range.start, range.end) || compactDate(base.dateLabel || base.dateCompact);
  const detailMetaLine = isSourceOverview ? "" : [cityLabel, rangeLabel].filter(Boolean).join(" · ");
  const calendarPreviewLabel = base.isCalendarPreview ? (safeLang === "zh" ? (base.calendarPreviewLabel || "活动一览") : "Preview") : "";
  const localized = {
    ...base,
    rawCityLabel,
    rawCardLocationLabel: rawCardLocation,
    rawPriceItems,
    cityLabel,
    cardLocationLabel: isSourceOverview ? "" : cardLocationLabel,
    dateRangeLabel: rangeLabel,
    dateRangeCompact: dateCompactLabel,
    dateCompact: dateCompactLabel,
    weekdayLabel: weekday,
    dateDisplay: [weekday, dateCompactLabel].filter(Boolean).join(" "),
    detailMetaLine,
    calendarPreviewLabel,
    price: priceItems,
    priceLabel: priceItems.join(" / "),
    lineupHint: text("detail", safeLang).lineupHint,
  };
  if (localized.clubProfile) {
    localized.clubProfile = { ...localized.clubProfile, cityLabel };
  }
  if (localized.sourceArticles) {
    localized.sourceArticles = localizedSourceArticles(localized.sourceArticles, safeLang);
  }
  return localized;
}

function localizeItems(items, lang) {
  return (Array.isArray(items) ? items : []).map((item) => localizeItem(item, lang));
}

function applyLanguageChrome(scope, lang) {
  if (typeof wx === "undefined") return;
  const safeLang = normalizeLang(lang);
  const title = NAV_TITLES[scope]?.[safeLang];
  if (title && typeof wx.setNavigationBarTitle === "function") {
    try {
      wx.setNavigationBarTitle({ title });
    } catch {}
  }
  if (typeof wx.setTabBarItem === "function") {
    const labels = TAB_LABELS[safeLang];
    labels.forEach((label, index) => {
      try {
        wx.setTabBarItem({ index, text: label });
      } catch {}
    });
  }
}

